"""Builds the Arduino IDE sketch, arduino/local_esp32_ai/, from the firmware.

    python firmware/make_arduino.py           # after changing the engine or the model
    python firmware/make_arduino.py --check   # exit 1 if the sketch is out of date (test.sh)

The sketch is generated so the Arduino IDE needs nothing but itself: the
engine is copied into its src/ folder, the model becomes a C file (the IDE
has no build scripts to embed a binary), and two files carry the settings
PlatformIO's platformio.ini holds:
    partitions.csv  one 3.9 MB app partition (Tools > Partition Scheme > Custom)
    build_opt.h     compiler flags: -ffp-contract=off keeps the floats
                    bit-identical to the PC build the tests run
"""

import argparse
import filecmp
import os
import shutil
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
NAME = "local_esp32_ai"  # an Arduino sketch's folder and .ino share its name
OUT = os.path.join(ROOT, "arduino", NAME)


def c_string(data, width=120):
    """Bytes as C string literal lines: printable characters as themselves,
    everything else as 3-digit octal (so a following digit can't join it)."""
    lines, line = [], []
    n = 0
    for b in data:
        ch = chr(b)
        if 32 <= b < 127 and ch not in '\\"?':
            piece = ch
        else:
            piece = "\\%03o" % b
        line.append(piece)
        n += len(piece)
        if n >= width:
            lines.append('    "' + "".join(line) + '"')
            line, n = [], 0
    if line:
        lines.append('    "' + "".join(line) + '"')
    return "\n".join(lines)


def build(out):
    src = os.path.join(out, "src")
    os.makedirs(src, exist_ok=True)
    main = open(os.path.join(HERE, "src", "main.cpp")).read()
    main = main.replace('#include "model_data.h"', '#include "src/model_data.h"')
    main = main.replace('#include "tinyai.h"', '#include "src/tinyai.h"')
    header = ("// Generated by firmware/make_arduino.py from firmware/src/main.cpp. Edit that\n"
              "// file and the engine in firmware/lib/tinyai/, then run the script.\n")
    with open(os.path.join(out, NAME + ".ino"), "w") as f:
        f.write(header + main)
    lib = os.path.join(HERE, "lib", "tinyai")
    for name in sorted(os.listdir(lib)):
        shutil.copyfile(os.path.join(lib, name), os.path.join(src, name))
    shutil.copyfile(os.path.join(HERE, "src", "model_data.h"), os.path.join(src, "model_data.h"))
    model = open(os.path.join(HERE, "data", "model.bin"), "rb").read()
    with open(os.path.join(src, "model_data.c"), "w") as f:
        f.write("// Generated by firmware/make_arduino.py from firmware/data/model.bin. Do not edit.\n"
                "#include \"model_data.h\"\n\n"
                f"const uint32_t model_data_size = {len(model)};\n"
                # exactly len(model) bytes: no terminating NUL (valid C, not C++)
                f"const uint8_t model_data[{len(model)}] __attribute__((aligned(16))) =\n"
                f"{c_string(model)};\n")
    shutil.copyfile(os.path.join(HERE, "partitions.csv"), os.path.join(out, "partitions.csv"))
    with open(os.path.join(out, "build_opt.h"), "w") as f:
        f.write("-O2\n-ffp-contract=off\n")


def same_tree(a, b):
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return False
    # dircmp compares by stat signature; recheck file contents
    if any(not filecmp.cmp(os.path.join(a, f), os.path.join(b, f), shallow=False) for f in cmp.same_files):
        return False
    return all(same_tree(os.path.join(a, d), os.path.join(b, d)) for d in cmp.common_dirs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="only check that the sketch is up to date")
    args = ap.parse_args()
    if not args.check:
        shutil.rmtree(OUT, ignore_errors=True)
        build(OUT)
        print(f"wrote {os.path.relpath(OUT, ROOT)}")
        return
    with tempfile.TemporaryDirectory() as tmp:
        fresh = os.path.join(tmp, NAME)
        build(fresh)
        if not os.path.isdir(OUT) or not same_tree(fresh, OUT):
            sys.exit(f"{os.path.relpath(OUT, ROOT)} is out of date: run python firmware/make_arduino.py")
    print(f"{os.path.relpath(OUT, ROOT)} is up to date")


if __name__ == "__main__":
    main()
